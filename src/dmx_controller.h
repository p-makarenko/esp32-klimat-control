// ============================================================================
// DMX_CONTROLLER.H - Керування DMX512 через RS485
// ============================================================================
// DMX512 фрейм: BREAK (~92мкс LOW) + MAB (~12мкс HIGH) + START byte(0x00)
//               + 512 каналів (0-255 кожен)
// UART: 250 kbps, 8N2
// RS485: GPIO TX → DE/RE пін для перемикання направлення
// ============================================================================

#ifndef DMX_CONTROLLER_H
#define DMX_CONTROLLER_H

#include <Arduino.h>

// ============================================================================
// ПІНИ - підбери під свою схему
// UART0 = Serial (USB монітор)
// UART2 = PZEM (Serial2, GPIO17/18) — не чіпати
// UART1 = вільний → використовуємо для DMX
// ============================================================================
#define DMX_TX_PIN      40      // Вільний GPIO (підключити до DI MAX485)
#define DMX_RX_PIN      36      // Вільний GPIO (не підключати)
#define DMX_DE_RE_PIN   37      // MAX485 DE пін
#define DMX_UART_NUM    1       // UART1 — вільний

// ============================================================================
// DMX ПАРАМЕТРИ
// ============================================================================
#define DMX_UPDATE_INTERVAL 100

// ============================================================================
// RGBW КАНАЛИ (налаштуй під адресу свого світильника)
// ============================================================================
#define DMX_START_ADDRESS   1       // Стартовий DMX-адрес світильника
#define DMX_CH_MASTER       0       // CH1: загальна яскравість (0=вимкнено, 255=повна)
#define DMX_CH_RED          1       // CH2: червоний
#define DMX_CH_GREEN        2       // CH3: зелений
#define DMX_CH_BLUE         3       // CH4: синій
#define DMX_CH_STROBE       4       // CH5: строб (0=вимкнено)
#define DMX_CH_WHITE        5       // CH6: color change (не використовується)
#define DMX_CH_COUNT        6       // Всього каналів

// ============================================================================
// СТРУКТУРА RGBW
// ============================================================================
struct RGBWColor {
    uint8_t r;
    uint8_t g;
    uint8_t b;
    uint8_t master;  // CH1: загальна яскравість
};

// ============================================================================
// ПУБЛІЧНИЙ API
// ============================================================================
void dmxInit();
void dmxSetRGBW(uint8_t r, uint8_t g, uint8_t b, uint8_t master = 255);
void dmxSetChannel(uint16_t channel, uint8_t value);
void dmxSendFrame();
void dmxTask(void* parameter);

// Поточний стан
RGBWColor dmxGetCurrent();

extern TaskHandle_t dmxTaskHandle;

#endif // DMX_CONTROLLER_H
